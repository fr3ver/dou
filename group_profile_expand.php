function dou_expand_group_education(string $band, array $meta, string $short): string
{
    $site = defined('SITE_NAME') ? SITE_NAME : 'детского сада';

    $program = match ($band) {
        'nursery' => 'адаптационно-игровой программы ясельной группы',
        'junior' => 'основной общеобразовательной программы дошкольного образования для младшей группы (3–4 года)',
        'middle' => 'основной общеобразовательной программы дошкольного образования для средней группы (4–5 лет)',
        'senior' => 'основной общеобразовательной программы дошкольного образования для старшей группы (5–7 лет) и программы предшкольной подготовки',
        'speech' => 'коррекционно-развивающей программы по преодолению речевых нарушений у детей дошкольного возраста',
        default => 'основной общеобразовательной программы дошкольного образования',
    };

    $focus = $short !== ''
        ? ', в которой особое внимание уделяется: ' . dou_mb_lcfirst(rtrim($short, '.'))
        : '';

    $ageNote = ($meta['range'] !== '' && $band !== 'speech')
        ? ' (возраст ' . $meta['range'] . ')'
        : '';

    return 'Обучение в группе осуществляется по образовательной программе, разработанной коллективом МАДОУ «'
        . $site
        . '» г. Улан-Удэ на основе ФОП ДО, в рамках '
        . $program
        . $ageNote
        . $focus
        . '.';
}

/** Группа уже оформлена вручную (все три блока заполнены). */
function dou_group_profile_is_complete(?string $description, ?string $activities, ?string $education): bool
{
    return trim((string)$description) !== ''
        && trim((string)$activities) !== ''
        && trim((string)$education) !== ''
        && mb_strlen(trim((string)$description)) >= 200;
}
