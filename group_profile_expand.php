function dou_mb_lcfirst(string $text): string
{
    if ($text === '') {
        return $text;
    }

    return mb_strtolower(mb_substr($text, 0, 1, 'UTF-8'), 'UTF-8') . mb_substr($text, 1, null, 'UTF-8');
}

/** Имя группы из «кавычек» в названии. */
function dou_group_nickname(string $name): string
{
    if (preg_match('/«([^»]+)»/u', $name, $m)) {
        return $m[1];
    }

    return trim($name);
}

/**
 * Развернуть профиль группы в стиле «Белочки» на основе краткого описания из БД.
 *
 * @return array{description: string, activities_features: string, education_program: string}
 */
function dou_expand_group_profile(string $name, ?string $ageCategory, string $shortDescription): array
{
    $short = trim(preg_replace('/\s+/u', ' ', $shortDescription));
    $band = dou_age_band($ageCategory);
    $meta = dou_age_band_meta($band);
    $nickname = dou_group_nickname($name);
    $groupRef = $nickname !== '' ? 'группы «' . $nickname . '»' : 'группы';

    $description = dou_expand_group_description($band, $meta, $groupRef, $short);
    $activities = dou_expand_group_activities($band, $groupRef, $short);
    $education = dou_expand_group_education($band, $meta, $short);

    return [
        'description' => $description,
        'activities_features' => $activities,
        'education_program' => $education,
    ];
}

