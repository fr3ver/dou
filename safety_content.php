/** @return list<array{title: string, body: string, file_ids?: list<int>}> */
function safety_canonical_units(array $fileIdsByUnit = []): array
{
    $units = [
        ['title' => 'Безопасность детей', 'body' => safety_children_body()],
        ['title' => 'Азбука безопасности', 'body' => safety_alphabet_body()],
        ['title' => 'Документы', 'body' => safety_documents_body()],
        ['title' => 'Правила пожарной безопасности', 'body' => safety_fire_rules_body()],
    ];

    foreach ($units as $idx => $unit) {
        $fileIds = array_values(array_filter($fileIdsByUnit[$unit['title']] ?? []));
        if ($fileIds !== []) {
            $units[$idx]['file_ids'] = $fileIds;
        }
    }

    return $units;
}

/** Добавляет в БД блоки, которых ещё нет (без перезаписи существующих). */
function safety_sync_missing_units(PDO $pdo): void
{
    require_once __DIR__ . '/svedeniya_structure.php';

    $row = org_document_text_get($pdo, 'safety');
    if (!$row) {
        return;
    }

    $parsed = svedeniya_structure_parse((string)$row['content']);
    $existingByTitle = [];
    foreach ($parsed['units'] as $unit) {
        $title = trim((string)($unit['title'] ?? ''));
        if ($title !== '') {
            $existingByTitle[$title] = $unit;
        }
    }

    $fileIdsByUnit = [];
    foreach ($parsed['units'] as $unit) {
        $title = trim((string)($unit['title'] ?? ''));
        $ids = svedeniya_structure_unit_file_ids($unit);
        if ($title !== '' && $ids !== []) {
            $fileIdsByUnit[$title] = $ids;
        }
    }
    $canonical = safety_canonical_units($fileIdsByUnit);
    $merged = [];
    $changed = false;

    foreach ($canonical as $unit) {
        $title = $unit['title'];
        if (isset($existingByTitle[$title])) {
            $merged[] = svedeniya_structure_normalize_unit($existingByTitle[$title]);
            continue;
        }
        $merged[] = $unit;
        $changed = true;
    }

    if (!$changed) {
        return;
    }

    $parsed['units'] = $merged;
    if (trim($parsed['intro']) === '') {
        $parsed['intro'] = safety_intro_text();
    }

    org_document_text_save($pdo, 'safety', 'Безопасность', svedeniya_structure_encode($parsed));
}
