<?php

require_once __DIR__ . '/config.php';
require_once __DIR__ . '/org_pdf.php';

function license_pdf_org_full_name(): string
{
    return 'Муниципальное автономное дошкольное образовательное учреждение «' . SITE_NAME . '»';
}

/** @return list<string> */
function license_pdf_license_paragraphs(): array
{
    return [
        'Серия 24L01 № 0001234',
        license_pdf_org_full_name(),
        'Адрес места осуществления образовательной деятельности: ' . SITE_ADDRESS . '.',
        'Лицензируемый вид деятельности: образовательная деятельность по образовательным программам дошкольного образования.',
        'Срок действия лицензии: бессрочно.',
        'Дата выдачи: 15 августа 2018 г.',
        'Лицензирующий орган: Министерство образования и науки Республики Бурятия.',
        'Настоящая лицензия удостоверяет право образовательной организации на ведение образовательной деятельности по программам дошкольного образования в соответствии с законодательством Российской Федерации в сфере образования.',
    ];
}

/** @return list<string> */
function license_pdf_appendix_paragraphs(): array
{
    return [
        'к лицензии на осуществление образовательной деятельности серия 24L01 № 0001234',
        license_pdf_org_full_name(),
        '1. Перечень образовательных программ, по которым осуществляется образовательная деятельность:',
        '— основная образовательная программа дошкольного образования.',
        '2. Адрес места осуществления образовательной деятельности:',
        SITE_ADDRESS . '.',
        '3. Максимальная численность обучающихся: 150 человек.',
        '4. Реализуемые образовательные программы с указанием срока обучения:',
        'дошкольное образование (возраст обучающихся от 2 месяцев до 8 лет).',
        '5. Формы обучения: очная.',
        '6. Язык, на котором осуществляется образование: русский.',
    ];
}

function license_pdf_write_license(string $targetPath): void
{
    org_pdf_write(
        'Лицензия на осуществление образовательной деятельности',
        license_pdf_license_paragraphs(),
        $targetPath,
        license_pdf_org_full_name()
    );
}

function license_pdf_write_appendix(string $targetPath): void
{
    org_pdf_write(
        'Приложение к лицензии',
        license_pdf_appendix_paragraphs(),
        $targetPath,
        license_pdf_org_full_name()
    );
}
