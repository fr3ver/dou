/** @return list<array{title: string, body: string, file_ids?: list<int>}> */
function parents_info_canonical_units(PDO $pdo): array
{
    $slug = 'parents_info';
    $fileIdsByKey = [];
    $stmt = $pdo->prepare("
        SELECT id, category FROM org_documents
        WHERE item_type = 'file' AND section_slug = ? AND is_published = 1
    ");
    $stmt->execute([$slug]);
    foreach ($stmt->fetchAll(PDO::FETCH_ASSOC) as $row) {
        $fileIdsByKey[(string)$row['category']] = (int)$row['id'];
    }

    $mentoringIds = [];
    foreach (array_column(parents_info_mentoring_documents(), 'key') as $key) {
        if (isset($fileIdsByKey[$key])) {
            $mentoringIds[] = $fileIdsByKey[$key];
        }
    }

    $healthIds = [];
    foreach (array_column(parents_info_health_documents(), 'key') as $key) {
        if (isset($fileIdsByKey[$key])) {
            $healthIds[] = $fileIdsByKey[$key];
        }
    }

    $units = parents_info_canonical_units_static();

    if ($mentoringIds !== []) {
        $units[0]['file_ids'] = $mentoringIds;
    }
    if ($healthIds !== []) {
        $units[3]['file_ids'] = $healthIds;
    }

    return $units;
}

/** Добавляет в БД блоки, которых ещё нет (без перезаписи существующих). */
function parents_info_sync_missing_units(PDO $pdo): void
{
    require_once __DIR__ . '/svedeniya_structure.php';

    $row = org_document_text_get($pdo, 'parents_info');
    if (!$row) {
        return;
    }

    $parsed = svedeniya_structure_parse((string)$row['content']);
    $existingByTitle = [];
    foreach ($parsed['units'] as $unit) {
        $title = trim((string)($unit['title'] ?? ''));
        if ($title !== '') {
            $existingByTitle[$title] = $unit;
        }
    }

    $canonical = parents_info_canonical_units($pdo);
    $merged = [];
    $changed = false;

    foreach ($canonical as $unit) {
        $title = $unit['title'];
        if (isset($existingByTitle[$title])) {
            $merged[] = svedeniya_structure_normalize_unit($existingByTitle[$title]);
            continue;
        }
        $merged[] = $unit;
        $changed = true;
    }

    if (!$changed) {
        return;
    }

    $parsed['units'] = $merged;
    if (trim($parsed['intro']) === '') {
        $parsed['intro'] = parents_info_intro_text();
    }

    org_document_text_save($pdo, 'parents_info', 'Информация для родителей', svedeniya_structure_encode($parsed));
}
