    return match ($band) {
        'nursery' => menu_pdf_nursery_day($weekday),
        'junior'  => menu_pdf_junior_day($weekday),
        'middle'  => menu_pdf_middle_day($weekday),
        default   => menu_pdf_senior_day($weekday),
    };
}
