function menu_pdf_scale_weight(int $weight, float $factor): int
{
    return max(25, (int) round($weight * $factor));
}

/**
 * @param list<array{0: string, 1: string, 2: int, 3: string}> $meals
 * @return list<array{0: string, 1: string, 2: int, 3: string}>
 */
function menu_pdf_scale_meals(array $meals, float $factor): array
{
    $out = [];
    foreach ($meals as [$type, $dish, $weight, $allergies]) {
        $out[] = [$type, $dish, menu_pdf_scale_weight($weight, $factor), $allergies];
    }

    return $out;
}

