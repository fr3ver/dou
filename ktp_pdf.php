<?php

require_once __DIR__ . '/org_pdf.php';
require_once __DIR__ . '/ktp_catalog.php';

/** @return list<string> */
function ktp_pdf_paragraphs(array $item): array
{
    $org = 'МАДОУ «' . SITE_NAME . '»';
    $title = $item['title'];
    $type = $item['type'] ?? 'week';
    $group = ktp_group_definitions()[$item['group']]['title'] ?? '';

    $base = [
        $org,
        $title,
        'Документ подготовлен для планирования образовательной деятельности в соответствии с ФГОС ДО и федеральной образовательной программой дошкольного образования (ФОП ДО).',
        'Возрастная группа: ' . $group . '.',
    ];

    return match ($type) {
        'monthly' => array_merge($base, [
            'Календарно-тематический план включает цели и задачи на месяц, темы недель, образовательные области, формы работы с детьми, взаимодействие с семьёй.',
            'Планирование учитывает индивидуальные особенности воспитанников, сезонность и режим дня группы.',
            'Воспитатель использует план при составлении ежедневных и недельных записей в рабочей программе.',
        ]),
        'program' => array_merge($base, [
            'Рабочая программа определяет планируемые результаты освоения программы, содержание, организацию образовательной деятельности и условия её реализации.',
            'Программа согласована с основной образовательной программой дошкольного образования учреждения.',
        ]),
        'perspective', 'summer' => array_merge($base, [
            'Перспективный план отражает основные направления работы на период, тематику недель, праздники и проекты.',
            'План служит основой для календарно-тематического планирования воспитателя.',
        ]),
        default => array_merge($base, [
            'Тематическая неделя включает цель, задачи, содержание образовательной деятельности по областям развития, игровую и предметно-развивающую среду.',
            'Предусмотрены утренние и вечерние круги общения, НОД, прогулки, самостоятельная деятельность детей и работа с родителями.',
        ]),
    };
}

function ktp_pdf_write(array $item, string $targetPath): void
{
    org_pdf_write($item['title'], ktp_pdf_paragraphs($item), $targetPath, SITE_NAME);
}

function ktp_pdf_target_dir(): string
{
    return __DIR__ . '/../uploads/org_docs/ktp/';
}

function ktp_pdf_relative_path(string $basename): string
{
    return 'uploads/org_docs/ktp/' . $basename;
}
